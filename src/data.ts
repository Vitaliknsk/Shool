export function GROUPS() {
  const mk = (offsetMonths: number) => {
    const now = new Date();
    const d = new Date(now.getFullYear(), now.getMonth() + offsetMonths, 1);
    while (d.getDay() !== 1) d.setDate(d.getDate() + 1);
    return d;
  };
  const fmtDate = (d: Date) => d.toLocaleDateString("ru-RU", { day: "numeric", month: "long" });
  return [
    { date: fmtDate(mk(0)), schedule: "Пн · Ср · Пт, 19:00", left: 4 },
    { date: fmtDate(mk(1)), schedule: "Вт · Чт, 18:30 + Сб 10:00", left: 7 },
    { date: fmtDate(mk(2)), schedule: "Сб · Вс, 10:00 (утренняя)", left: 11 },
  ];
}

